def main() -> int:
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
    from realign.web import i18n

    added_ar = [k for k in AR if k not in i18n.AR]
    added_en = [k for k in EN if k not in i18n.EN]

    i18n.AR.update({k: v for k, v in AR.items() if k in added_ar})
    i18n.EN.update({k: v for k, v in EN.items() if k in added_en})

    path = pathlib.Path("realign/web/i18n.py")
    src = path.read_text(encoding="utf-8")

    for name, table, added in (("AR", AR, added_ar), ("EN", EN, added_en)):
        if not added:
            continue
        block = "".join(
            '    "%s": %s,\n' % (k, _py_str(table[k])) for k in added
        )
        # Append right before the closing brace of the dict literal.
        pattern = re.compile(
            r'(\n' + name + r':\s*dict\[str,\s*str\]\s*=\s*\{.*?\n)(\}\n)',
            re.DOTALL,
        )
        m = pattern.search(src)
        if m is None:
            print(f"!! could not locate the {name} dict literal")
            return 1
        src = src[: m.end(1)] + block + src[m.end(1) :]

    path.write_text(src, encoding="utf-8")
    print(f"added AR: {len(added_ar)}  EN: {len(added_en)}")
    return 0


def _py_str(value: str) -> str:
    """Emit a Python string literal with escaped quotes and newlines."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


