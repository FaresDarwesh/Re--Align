STRINGS: dict[str, dict[str, str]] = {"ar": AR, "en": EN}

_FMT = Formatter()


def normalise(lang: str | None) -> str:
    """Map any input onto a supported code, defaulting to Arabic."""
    if not lang:
        return DEFAULT_LANG
    code = str(lang).strip().lower().replace("_", "-")
    base = code.split("-")[0]
    if base in SUPPORTED:
        return base
    if code in SUPPORTED:
        return code
    return DEFAULT_LANG


def translate(lang: str | None, key: str, **params) -> str:
    """Look up `key`. Never raises; falls back ar → en → the key itself."""
    code = normalise(lang)
    table = STRINGS.get(code, {})
    value = table.get(key)
    if value is None:
        value = EN.get(key)
    if value is None:
        value = AR.get(key, key)
    if params:
        try:
            value = value.format(**params)
        except (KeyError, IndexError, ValueError):
            pass
    return value


def dir_for(lang: str | None) -> str:
    return DIRS.get(normalise(lang), "rtl")


def missing_keys() -> dict[str, list[str]]:
    """Keys present in one language but not the other (used by the tests)."""
    only_ar = sorted(set(AR) - set(EN))
    only_en = sorted(set(EN) - set(AR))
    return {"only_ar": only_ar, "only_en": only_en}


