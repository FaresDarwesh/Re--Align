@router.post("/cookies")
async def cookie_settings_save(request: Request):
    from realign.core.sanitize import clamp_int

    form = await request.form()
    choice = str(form.get("choice") or "reject")
    if choice not in ("accept", "reject"):
        choice = "reject"
    days = clamp_int(180 if choice == "accept" else 30, minimum=1, maximum=365, default=30)
    response: Response = RedirectResponse(url="/cookies?saved=1", status_code=303)
    response.set_cookie(
        "ra_cookie_consent",
        choice,
        max_age=days * 24 * 3600,
        httponly=False,
        secure=settings.effective_cookie_secure,
        samesite="lax",
        path="/",
    )
    return response


